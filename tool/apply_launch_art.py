#!/usr/bin/env python3
"""Applies the SuperCalculator launch artwork to the generated Android host.

The repository intentionally does not commit the Flutter platform folders: they
are regenerated by ``tool/bootstrap_flutter_platforms.sh`` so the exact stable
SDK owns the runner templates. Anything custom therefore has to be re-applied
after generation, which is what this script does.

It copies the drawable/theme resources that implement the Android 12+ animated
splash screen (and the legacy pre-12 launch background) and points the main
activity at ``Theme.SuperCalc.Splash``.

Usage:
    python3 tool/apply_launch_art.py            # apply (idempotent)
    python3 tool/apply_launch_art.py --check    # verify, non-zero if missing
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_RES = ROOT / "tool" / "platform_templates" / "android" / "res"
ANDROID_MAIN = ROOT / "flutter" / "android" / "app" / "src" / "main"
ANDROID_RES = ANDROID_MAIN / "res"
MANIFEST = ANDROID_MAIN / "AndroidManifest.xml"

SPLASH_THEME = "@style/Theme.SuperCalc.Splash"
LAUNCH_THEME = "@style/LaunchTheme"

REQUIRED_FILES = (
    "res/values/sc_splash.xml",
    "res/values-v31/sc_splash.xml",
    "res/values/sc_colors.xml",
    "res/values-night/sc_colors.xml",
    "res/drawable/sc_splash_glyph.xml",
    "res/drawable/sc_splash_icon.xml",
    "res/drawable/launch_background.xml",
    "res/drawable-v21/launch_background.xml",
)


def fail(message: str) -> int:
    print(f"error: {message}", file=sys.stderr)
    return 1


def copy_resources() -> list[str]:
    copied: list[str] = []
    for source in sorted(TEMPLATE_RES.rglob("*")):
        if not source.is_file():
            continue
        relative = source.relative_to(TEMPLATE_RES)
        target = ANDROID_RES / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        copied.append(str(target.relative_to(ROOT)))
    return copied


def patch_manifest() -> str:
    text = MANIFEST.read_text(encoding="utf-8")
    if SPLASH_THEME in text:
        return "already points at the splash theme"
    if text.count(LAUNCH_THEME) != 1:
        raise SystemExit(
            f"error: expected exactly one {LAUNCH_THEME} in {MANIFEST}, "
            f"found {text.count(LAUNCH_THEME)}"
        )
    MANIFEST.write_text(text.replace(LAUNCH_THEME, SPLASH_THEME), encoding="utf-8")
    return "activity theme -> splash theme"


def check() -> int:
    missing = [name for name in REQUIRED_FILES if not (ANDROID_MAIN / name).is_file()]
    if missing:
        return fail(
            "missing launch artwork: "
            + ", ".join(missing)
            + " (run this script after generating the platform folders)"
        )
    if MANIFEST.is_file() and SPLASH_THEME not in MANIFEST.read_text(encoding="utf-8"):
        return fail(f"AndroidManifest.xml does not use {SPLASH_THEME}")
    print("launch artwork: ok")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the platform folder already carries the launch artwork",
    )
    args = parser.parse_args()

    if args.check:
        return check()

    if not ANDROID_MAIN.is_dir():
        return fail(
            "flutter/android is missing; run tool/bootstrap_flutter_platforms.sh first"
        )

    copied = copy_resources()
    change = patch_manifest()
    print(f"launch artwork: {len(copied)} resource files copied ({change})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
